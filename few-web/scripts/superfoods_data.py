def price(store, product, low, high=None, unit=None, approximate=False):
    return {
        "store": store,
        "product": product,
        "price_min": low,
        "price_max": high if high is not None else low,
        "unit": unit,
        "approximate": approximate,
        "checked_date": None,
    }


def nutri(as_written, **fields):
    data = {"basis": "per 100 g", "as_written": as_written}
    data.update(fields)
    return data


