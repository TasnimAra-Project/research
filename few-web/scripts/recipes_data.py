def ev(pairs):
    found = {}
    ordered = []
    for label, url, description in pairs:
        if url in found:
            current = found[url]
            if description and not current["description"]:
                current["description"] = description
            continue
        item = {"label": label, "url": url, "description": description}
        found[url] = item
        ordered.append(item)
    return ordered


